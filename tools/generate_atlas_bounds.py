#!/usr/bin/env python3
"""Generate per-cell alpha bounds so runtime sprites sit on their visible ground pixels."""
from pathlib import Path
import argparse
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SPECS = {
    "FLORA_ATLAS_BOUNDS": ("assets/environment/flora_props_atlas_128.png", 128, 8, 6),
    "CLIFF_ATLAS_BOUNDS": ("assets/environment/cliffs_fences_atlas_128.png", 128, 8, 4),
    "STRUCTURE_ATLAS_BOUNDS": ("assets/environment/structures_atlas_128.png", 128, 8, 2),
    "ORIGINAL_PROPS_BOUNDS": ("assets/environment/original_props_16_v1.png", 32, 4, 4),
    "AREA_PROPS_BOUNDS": ("assets/environment/area_props_96.png", 96, 16, 1),
    "ENV_PROPS_BOUNDS": ("assets/environment/environment_props_96.png", 96, 12, 1),
    "PIXEL_PROPS_BOUNDS": ("assets/tiles/png/environment_props.png", 64, 12, 1),
}

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=ROOT / "build" / "generated" / "atlas_bounds.h")
    out = parser.parse_args().output
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "/* Generated by tools/generate_atlas_bounds.py. Do not edit. */",
        "#ifndef MIST_ISLE_ATLAS_BOUNDS_H",
        "#define MIST_ISLE_ATLAS_BOUNDS_H",
        "typedef struct { int x, y, w, h; } MistAtlasBounds;",
    ]
    for name, (rel, cell, cols, rows) in SPECS.items():
        path = ROOT / rel
        if not path.exists():
            raise SystemExit(f"Missing atlas required for alpha bounds: {rel}")
        with Image.open(path) as im:
            alpha = im.convert("RGBA").getchannel("A")
            if im.width < cols * cell or im.height < rows * cell:
                raise SystemExit(f"Atlas dimensions too small for {rel}: {im.size}")
            vals = []
            for row in range(rows):
                for col in range(cols):
                    box = (col * cell, row * cell, (col + 1) * cell, (row + 1) * cell)
                    bbox = alpha.crop(box).getbbox()
                    if bbox is None:
                        vals.append((0, 0, cell, cell))
                    else:
                        x0, y0, x1, y1 = bbox
                        vals.append((x0, y0, x1 - x0, y1 - y0))
        lines.append(f"static const MistAtlasBounds {name}[{len(vals)}] = {{")
        lines.extend("    {%d, %d, %d, %d}," % v for v in vals)
        lines.append("};")
    lines.append("#endif")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Generated {out.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
